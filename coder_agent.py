if __name__ == "__main__":

    print("=" * 70)
    print("🤖 AUTONOMOUS AI SOFTWARE ENGINEER")
    print("=" * 70)

    requirement = input(
        "\nWhat software do you want to build?\n> "
    )

    # Planner
    plan = create_plan(requirement)

    # Architect
    architecture = create_architecture(plan)

    # Convert requirement into a safe folder name
    project_name = (
        requirement
        .replace(" ", "_")
        .replace("/", "_")
        .replace("\\", "_")
        .replace(":", "")
        .replace("?", "")
    )

    project_path = create_project_structure(
        project_name,
        architecture
    )

    print("\n" + "=" * 70)
    print("📦 PROJECT CREATED")
    print("=" * 70)

    print(f"\nProject location:")
    print(project_path)

    print("\n✅ Coding Agent finished.")